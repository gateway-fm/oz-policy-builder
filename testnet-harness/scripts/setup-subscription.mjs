// Extra disposable W2 fixtures: a reviewed policy instance if requested, and an issued SAC
// funded only for this run's controlled account. This command submits testnet transactions.
import { randomBytes } from 'node:crypto';
import { join } from 'node:path';
import { Address, Asset, Operation, scValToNative, xdr } from '@stellar/stellar-sdk';
import { isMainModule } from './cli-entry.mjs';
import { delegatedSigner, externalSigner, i128 } from './lib.mjs';
import { configureSubscription, SPENDING_LIMIT_WASM } from './subscription.mjs';
import * as rpc from './rpc.mjs';

export async function setupSubscription(dir, { policy, period }, deps = rpc) {
  if (!Number.isInteger(Number(period)) || Number(period) < 12 || Number(period) > 120) throw new Error('period must be 12..120 ledgers');
  const path = join(dir, 'run.json');
  let run = deps.readJson(path);
  if (run.subscription !== undefined || run.tx?.create_subscription_policy || run.tx?.create_control_token) throw new Error('subscription setup already started');
  if (run.network !== rpc.NETWORK_PASSPHRASE || run.sac !== rpc.NATIVE_SAC) throw new Error('subscription setup requires testnet native SAC run');
  await deps.assertTestnet();
  const payer = deps.loadKey('payer');
  if (payer.publicKey() !== run.payer) throw new Error('subscription fee payer differs');
  if (policy === 'deploy') {
    const created = await deps.submit(payer, Operation.createCustomContract({ address: new Address(run.payer),
      wasmHash: Buffer.from(SPENDING_LIMIT_WASM, 'hex'), salt: randomBytes(32) }), { stage: 'create subscription policy' });
    run.tx.create_subscription_policy = created.hash;
    deps.writeJson(path, run);
    policy = deps.contractIdOf(created.returnValue);
  }
  await configureSubscription(dir, { policy, period }, deps);
  run = deps.readJson(path);
  // A contract merchant accepts either SAC without a classic trustline. Give this new
  // disposable merchant the same controlled owner; never retain another signing seed.
  const owner = run.owner.kind === 'ed25519' ? delegatedSigner(run.owner.address)
    : run.owner.kind === 'passkey' ? externalSigner(run.owner.verifier, Buffer.from(run.owner.key_data, 'hex'))
      : (() => { throw new Error('unsupported merchant owner'); })();
  const merchant = await deps.submit(payer, Operation.createCustomContract({ address: new Address(run.payer),
    wasmHash: Buffer.from(rpc.PINNED_ACCOUNT_WASM, 'hex'), salt: randomBytes(32),
    constructorArgs: [xdr.ScVal.scvVec([owner]), xdr.ScVal.scvMap([])] }), { stage: 'create subscription merchant' });
  run.tx.create_subscription_merchant = merchant.hash;
  deps.writeJson(path, run);
  run.recipient = deps.contractIdOf(merchant.returnValue);
  deps.writeJson(path, run);
  if (run.recipient === run.account || run.recipient === run.sac || run.recipient === run.subscription.policy_address) {
    throw new Error('subscription merchant must be a separate contract');
  }
  if (await deps.contractCodeHash(run.recipient) !== rpc.PINNED_ACCOUNT_WASM) throw new Error('merchant code differs');
  // A unique throwaway payer is already generated by setup.mjs. Its asset is separate from
  // native XLM; minting to the contract needs no classic trustline and cannot credit a third party.
  const asset = new Asset('W2TEST', run.payer);
  const token = asset.contractId(rpc.NETWORK_PASSPHRASE);
  const created = await deps.submit(payer, Operation.createStellarAssetContract({ asset }), { stage: 'create control token' });
  run.tx.create_control_token = created.hash;
  run.subscription.other_token = token;
  deps.writeJson(path, run);
  if (deps.contractIdOf(created.returnValue) !== token) throw new Error('control token identity differs');
  const minted = await deps.submit(payer, Operation.invokeContractFunction({ contract: token, function: 'mint',
    args: [new Address(run.account).toScVal(), i128(BigInt(run.amount))] }), { stage: 'mint control token' });
  run.tx.mint_control_token = minted.hash;
  deps.writeJson(path, run);
  const balance = scValToNative(await deps.viewCall(payer, token, 'balance', [new Address(run.account).toScVal()]));
  if (balance !== BigInt(run.amount)) throw new Error('control token was not funded as expected');
  run.subscription.control_token_funding = 'matched';
  deps.writeJson(path, run);
  return run.subscription;
}

if (isMainModule(import.meta.url)) {
  const options = rpc.args();
  if (!options['run-dir'] || !options.policy || !options['period-ledgers']) throw new Error('usage: setup-subscription.mjs --run-dir DIRECTORY --policy CONTRACT|deploy --period-ledgers 12..120');
  await setupSubscription(options['run-dir'], { policy: options.policy, period: options['period-ledgers'] });
}
